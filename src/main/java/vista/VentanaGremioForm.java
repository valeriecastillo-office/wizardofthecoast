private void simularCombate() {

    try {

        if (controlador.getAventureros().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Primero registra aventureros.");
            return;
        }

        StringBuilder resultados = new StringBuilder();

        for (String resultado : controlador.simularCombate()) {
            resultados.append(resultado).append("\n\n");
        }

        txtResultados.setText(resultados.toString());

    } catch (IOException e) {

        JOptionPane.showMessageDialog(this, "Error al guardar el combate: " + e.getMessage());

    }
}

