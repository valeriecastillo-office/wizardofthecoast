    private void registrarAventurero() {

    try {

        String nombre = txtNombre.getText().trim();
        int nivel = Integer.parseInt(txtNivel.getText().trim());
        int vida = Integer.parseInt(txtVida.getText().trim());
        String especial = txtEspecial.getText().trim();

        String clase = cbClase.getSelectedItem().toString();

        Aventurero aventurero;

        switch (clase) {

            case "Guerrero":
                aventurero = new Guerrero(nombre, nivel, vida, leerBooleano(especial));
                break;

            case "Mago":
                aventurero = new Mago(nombre, nivel, vida, Integer.parseInt(especial));
                break;

            case "Clérigo":
                aventurero = new Clerigo(nombre, nivel, vida, especial);
                break;

            case "Monje":
                aventurero = new Monje(nombre, nivel, vida, Integer.parseInt(especial));
                break;

            case "Paladín":
                aventurero = new Paladin(nombre, nivel, vida, Integer.parseInt(especial));
                break;

            case "Explorador":
                aventurero = new Explorador(nombre, nivel, vida, especial);
                break;

            case "Pícaro":
                aventurero = new Picaro(nombre, nivel, vida, leerBooleano(especial));
                break;

            default:
                aventurero = new Bardo(nombre, nivel, vida, especial);
                break;
        }

        controlador.registrarAventurero(aventurero);

        actualizarTabla();
        limpiarCampos();

        JOptionPane.showMessageDialog(this, "Aventurero registrado correctamente.");

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this, "Debes ingresar números enteros en los campos numéricos.");

    } catch (IllegalArgumentException | IOException e) {

        JOptionPane.showMessageDialog(this, e.getMessage());

    }
}
    private boolean leerBooleano(String texto) {
    texto = texto.trim().toLowerCase();
    return texto.equals("si") || texto.equals("sí") || texto.equals("true") || texto.equals("1");
}
  private void limpiarCampos() {
    txtNombre.setText("");
    txtNivel.setText("");
    txtVida.setText("");
    txtEspecial.setText("");
    cbClase.setSelectedIndex(0); // Vuelve a seleccionar la primera clase 
    txtNombre.requestFocus();    
}  
private void actualizarTabla() {

    modeloTabla.setRowCount(0);

    for (Aventurero aventurero : controlador.getAventureros()) {

        modeloTabla.addRow(new Object[]{
            aventurero.getClase(),
            aventurero.getNombre(),
            aventurero.getNivel(),
            aventurero.getPuntosVida(),
            obtenerAtributo(aventurero)
        });

    }
}

private String obtenerAtributo(Aventurero aventurero) {

    if (aventurero instanceof Guerrero) {
        return String.valueOf(((Guerrero) aventurero).isArmaduraPesada());
    }

    if (aventurero instanceof Mago) {
        return String.valueOf(((Mago) aventurero).getEspaciosConjuro());
    }

    if (aventurero instanceof Clerigo) {
        return ((Clerigo) aventurero).getDiosVenerado();
    }

    if (aventurero instanceof Monje) {
        return String.valueOf(((Monje) aventurero).getPuntosKi());
    }

    if (aventurero instanceof Paladin) {
        return String.valueOf(((Paladin) aventurero).getPuntosFuerza());
    }

    if (aventurero instanceof Explorador) {
        return ((Explorador) aventurero).getTerrenoFavorecido();
    }

    if (aventurero instanceof Picaro) {
        return String.valueOf(((Picaro) aventurero).isHerramientasLadron());
    }

    if (aventurero instanceof Bardo) {
        return ((Bardo) aventurero).getInstrumentoMusical();
    }

    return "";
}

